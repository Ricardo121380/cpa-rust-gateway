// Run in ego-browser nodejs with PRISM_M3={spaceId, receipts}; uses only an
// owned synthetic loopback gateway. Faults affect local read responses only.
const fs = await import("node:fs/promises");
const path = await import("node:path");
const {spaceId,receipts}=globalThis.PRISM_M3;
const info=JSON.parse(await fs.readFile(path.join(receipts,"local-preview.json"),"utf8"));
if(!info.synthetic||!info.root.includes("prism-complete-local-"))throw Error("Synthetic gateway required");
const origin=`http://127.0.0.1:${info.admin_port}`;
const page=(await taskSpace(spaceId)).page("p1");
if(new URL(await page.url()).origin!==origin)throw Error("Unexpected browser origin");
const checks=[];
const save=async(name)=>{
 await page.evaluate(async()=>{await document.fonts.ready;await Promise.all(document.getAnimations().filter(a=>a.effect?.getComputedTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{})));});
 await page.screenshot({path:path.join(receipts,`${name}.png`)});
};
const install=()=>{
  const original=window.fetch.bind(window);
  window.__m3Read={mode:"",calls:[]};
  window.fetch=async(...args)=>{
    const url=new URL(args[0] instanceof Request?args[0].url:String(args[0]),location.href);
    if(url.origin===location.origin&&url.pathname==="/admin/requests/summary"){
      const state=window.__m3Read;
      state.calls.push({cursor:url.searchParams.has("cursor"),mode:state.mode});
      if(state.mode==="read"||(state.mode==="next"&&url.searchParams.has("cursor")))return new Response(JSON.stringify({error:{code:"management_operations_busy"}}),{status:503,headers:{"Content-Type":"application/json"}});
      const response=await original(...args);
      if(state.mode==="render"&&response.ok){const body=await response.clone().json();return new Response(JSON.stringify({...body,items:null}),{status:200,headers:response.headers});}
      return response;
    }
    return original(...args);
  };
};
const {identifier}=await page.cdp("Page.addScriptToEvaluateOnNewDocument",{source:`(${install.toString()})();`});
console.log({faultScript:identifier});
await page.reload();
await page.waitForSelector('input[name="password"]',{state:"visible"});
await page.fill('input[name="password"]',(await fs.readFile(path.join(info.root,"qa-password"),"utf8")).trim());
