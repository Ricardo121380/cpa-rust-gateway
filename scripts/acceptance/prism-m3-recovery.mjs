if(!/^UI-[0-9a-f]{8}$/.test(recovery.reference)||/TypeError|at https?:|Unexpected Application Error/.test(recovery.text))throw Error("Unsafe render error");
await save("render-recovery");
await page.evaluate(()=>{window.__m3Read.mode="";});
await page.click('loc=role:button[name="重新打开页面"]');
await page.waitForFunction(()=>document.querySelectorAll(".request-table tbody tr").length===50);
checks.push("render exception shows safe reference, reopening same route recovers without writes");
await page.click('loc=css:.request-table tbody tr:first-child button');
