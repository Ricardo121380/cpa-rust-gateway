await page.click('loc=role:button[name="登录"]');
await page.waitForSelector("main.canvas",{state:"visible"});
await page.goto(`${origin}/admin-ui/#/monitoring`);
await page.waitForFunction(()=>document.querySelectorAll(".request-table tbody tr").length===50);
const rows=()=>page.evaluate(()=>document.querySelectorAll(".request-table tbody tr").length);
await page.evaluate(()=>{window.__m3Read.mode="next";});
await page.click('loc=role:button[name="加载更多"]');
await page.waitForFunction(()=>document.body.innerText.includes("下一页读取失败"));
if(await rows()!==50)throw Error("Next-page failure discarded rows");
await save("next-page-failure");
await page.evaluate(()=>{window.__m3Read.mode="";window.__m3Read.calls=[];});
await page.click('loc=role:button[name="重试下一页"]');
await page.waitForFunction(()=>document.querySelectorAll(".request-table tbody tr").length===57);
const retried=await page.evaluate(()=>window.__m3Read.calls);
if(retried.length!==1||!retried[0].cursor)throw Error("Next-page retry fetched unrelated pages");
checks.push("next-page failure retains 50 rows and retries exactly its cursor to 57");
await page.evaluate(()=>{window.__m3Read.mode="read";});
await page.click('loc=css:.request-read-actions button.secondary:first-child');
await page.waitForFunction(()=>document.body.innerText.includes("刷新失败"));
if(await rows()!==57)throw Error("Refresh failure discarded rows");
await save("refresh-failure");
await page.evaluate(()=>{window.__m3Read.mode="";});
await page.click('loc=css:.read-status button');
await page.waitForFunction(()=>!document.querySelector(".read-status")&&document.querySelectorAll(".request-table tbody tr").length===57);
checks.push("background refresh retains snapshot, timestamp and filters then recovers");
await page.evaluate(()=>{window.__m3Read.mode="read";});
await page.fill('input[name="model"]',"Exact/Model-v2");
await page.click('loc=role:button[name="应用筛选"]');
await page.waitForFunction(()=>document.querySelector(".read-status strong")?.textContent==="读取失败");
if(await page.evaluate(()=>document.querySelector('input[name="model"]').value)!=="Exact/Model-v2")throw Error("Filter lost");
await save("initial-failure");
await page.evaluate(()=>{window.__m3Read.mode="";});
await page.click('loc=css:.read-status button');
await page.waitForFunction(()=>document.querySelectorAll(".request-table tbody tr").length===50);
checks.push("first-read failure retains entered filter and recovers");
await page.evaluate(()=>{window.__m3Read.mode="render";});
